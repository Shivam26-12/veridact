"""
VERIDACT — Chain-of-Custody Tests

Verifies that custody entries are generated on case creation and status
changes, are returned chronologically, and are append-only: no existing
entry can be edited or deleted through the API.
"""


def _public_payload(**overrides):
    payload = {
        "title": "Unauthorised access to file server",
        "description": "An unknown account accessed the finance share overnight.",
        "incident_type": "unauthorized_access",
    }
    payload.update(overrides)
    return payload


def _create_case(client):
    response = client.post("/api/cases/anonymous", json=_public_payload())
    assert response.status_code == 201
    return response.json()


# ---------------------------------------------------------------------------
# Entries generated by business events
# ---------------------------------------------------------------------------

def test_case_creation_writes_case_created_entry(client, admin_headers):
    # Arrange / Act
    case = _create_case(client)

    # Assert
    logs = client.get(
        f"/api/cases/{case['id']}/custody", headers=admin_headers
    ).json()
    assert len(logs) == 1
    entry = logs[0]
    assert entry["action"] == "case_created"
    assert entry["case_id"] == case["id"]
    assert entry["performer_name"] is None
    assert case["case_number"] in entry["notes"]


def test_status_change_writes_case_updated_entry(
    client, users, case_factory, admin_headers
):
    # Arrange
    case = case_factory(assignee=users["inv1"], status="open")

    # Act
    client.patch(
        f"/api/cases/{case.id}",
        json={"status": "under_review"},
        headers=admin_headers,
    )

    # Assert
    logs = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()
    latest = logs[-1]
    assert latest["action"] == "case_updated"
    assert latest["performer_name"] == users["admin"].name
    assert "status: open" in latest["notes"]
    assert "under_review" in latest["notes"]


def test_severity_change_writes_case_updated_entry(
    client, users, case_factory, admin_headers
):
    # Arrange
    case = case_factory(assignee=users["inv1"], severity="medium")

    # Act
    client.patch(
        f"/api/cases/{case.id}",
        json={"severity": "critical"},
        headers=admin_headers,
    )

    # Assert
    logs = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()
    assert logs[-1]["action"] == "case_updated"
    assert "severity: medium" in logs[-1]["notes"]
    assert "critical" in logs[-1]["notes"]


def test_custody_entries_are_returned_chronologically(
    client, users, case_factory, admin_headers
):
    # Arrange
    case = case_factory(assignee=users["inv1"])
    client.patch(
        f"/api/cases/{case.id}", json={"status": "in_progress"}, headers=admin_headers
    )
    client.patch(
        f"/api/cases/{case.id}", json={"severity": "high"}, headers=admin_headers
    )

    # Act
    logs = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()

    # Assert
    timestamps = [entry["timestamp"] for entry in logs]
    assert timestamps == sorted(timestamps)
    assert [entry["action"] for entry in logs] == [
        "case_created",
        "case_updated",
        "case_updated",
    ]


