def test_existing_entries_are_never_modified_by_later_events(
    client, users, case_factory, admin_headers
):
    # Arrange
    case = case_factory(assignee=users["inv1"])
    before = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()

    # Act — two more audited events on the same case
    client.patch(
        f"/api/cases/{case.id}", json={"status": "in_progress"}, headers=admin_headers
    )
    client.patch(
        f"/api/cases/{case.id}", json={"severity": "critical"}, headers=admin_headers
    )
    after = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()

    # Assert — the log only grew; every earlier entry is byte-for-byte identical
    assert len(after) == len(before) + 2
    assert after[: len(before)] == before


def test_custody_log_exposes_no_update_or_delete_endpoint(
    client, users, case_factory, admin_headers
):
    # Arrange
    case = case_factory(assignee=users["inv1"])
    before = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()
    entry_id = before[0]["id"]

    # Act
    delete_response = client.delete(
        f"/api/admin/custody/{entry_id}", headers=admin_headers
    )
    update_response = client.patch(
        f"/api/admin/custody/{entry_id}",
        json={"notes": "tampered"},
        headers=admin_headers,
    )
    after = client.get(
        f"/api/cases/{case.id}/custody", headers=admin_headers
    ).json()

    # Assert
    assert delete_response.status_code == 404
    assert update_response.status_code == 404
    assert after == before


